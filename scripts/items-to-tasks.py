#!/usr/bin/env python3
"""One-time move: everyday tasks from the old `items` table into `tasks` (kind "task").

Usage (local or --remote):
  npx wrangler d1 execute DB --remote --json --command "SELECT * FROM items" > items.json
  python3 scripts/items-to-tasks.py items.json > items-to-tasks.sql
  npx wrangler d1 execute DB --remote --file items-to-tasks.sql

Safe to re-run: rows are keyed by legacy_ref ("x:<external_id>" or "item:<id>").
Mapping matches todoFields() in src/worker.js:
  due_at -> date + time in America/Chicago (9:00 = no time, the old convention)
  repeat_days -> repeat "custom", every N days
  nag hourly / 15m -> nag hourly; daily -> nag daily at its time; once -> no nag; none -> silent
  notes, area, person_id, trip_id, top3, source, kind=note -> details
  done items -> a task_log entry; reminders already sent -> task_nags (so nothing repeats)
"""
import json, sys
from datetime import datetime
from zoneinfo import ZoneInfo

TZ = ZoneInfo('America/Chicago')

def q(v):
    if v is None: return 'NULL'
    if isinstance(v, (int, float)): return str(v)
    return "'" + str(v).replace("'", "''") + "'"

def local(iso):
    d = datetime.fromisoformat(iso.replace('Z', '+00:00')).astimezone(TZ)
    return d.strftime('%Y-%m-%d'), d.strftime('%H:%M')

rows = json.load(open(sys.argv[1]))
if isinstance(rows, list) and rows and 'results' in rows[0]: rows = rows[0]['results']
out = ['-- Generated by scripts/items-to-tasks.py']
for it in rows:
    ref = 'x:' + it['external_id'] if it.get('external_id') else f"item:{it['id']}"
    date = time = None
    if it.get('due_at'):
        date, hm = local(it['due_at'])
        time = None if hm == '09:00' else hm
    det = {}
    for k in ('notes', 'area', 'source'):
        if it.get(k): det[k] = it[k]
    for k in ('person_id', 'trip_id'):
        if it.get(k): det[k] = it[k]
    if it.get('top3'): det['top3'] = 1
    if it.get('kind') == 'note': det['note'] = 1
    nag, mode, nag_time = 0, 'hourly', None
    if it.get('nag') in ('hourly', '15m'): nag = 1
    elif it.get('nag') == 'daily': nag, mode, nag_time = 1, 'daily', time or '09:00'
    elif it.get('nag') == 'none': det['silent'] = 1
    repeat, custom = 'never', None
    if it.get('repeat_days'):
        repeat, custom = 'custom', json.dumps({'freq': 'daily', 'interval_n': min(366, int(it['repeat_days']))})
    out.append(
        'INSERT OR IGNORE INTO tasks (user_id, shared, kind, title, details, date, time, repeat, custom, nag, nag_mode, nag_time, snooze_until, legacy_ref, created_at) VALUES ('
        + ', '.join(q(v) for v in (it.get('user_id') or 1, it.get('shared') or 0, 'task', it['title'], json.dumps(det), date, time, repeat, custom,
                                   nag, mode, nag_time, it.get('snooze_until'), ref, it.get('created_at') or datetime.utcnow().isoformat() + 'Z'))
        + ');')
    occ = (f'{date} {time}' if time else date) if date else None
    tid = f'(SELECT id FROM tasks WHERE legacy_ref = {q(ref)})'
    if it.get('status') == 'done':
        at = it.get('done_at') or it.get('created_at')
        key = occ or local(at)[0]
        out.append(f"INSERT OR IGNORE INTO task_log (task_id, occ, status, at, by_user) VALUES ({tid}, {q(key)}, 'done', {q(at)}, {q(it.get('user_id') or 1)});")
    elif it.get('notify_count') and it.get('last_notified_at') and occ:
        out.append(f"INSERT OR IGNORE INTO task_nags (key, last_at, count) VALUES ('todo:' || {tid} || ':{it.get('user_id') or 1}:{occ}', {q(it['last_notified_at'])}, {int(it['notify_count'])});")
# Focus mode pointed at an old item id
out.append("UPDATE settings SET value = '' WHERE key LIKE '%focus_item';")
print('\n'.join(out))
